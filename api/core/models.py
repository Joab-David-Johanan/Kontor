"""Database tables (SQLAlchemy 2 ORM).

Rules:
- every tenant-owned table has a tenant_id column, and its main index starts with tenant_id
- internal ids are UUIDs generated by Postgres; human-readable codes (C-1001, SUP-1046)
  come from Postgres sequences, so two simultaneous inserts can never get the same code
- the schema is created by Alembic migrations (migrations/versions/), not by create_all()
"""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    ARRAY,
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    MetaData,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from core.values import (
    CHANNELS,
    CONVERSATION_STATUSES,
    ISSUE_CATEGORIES,
    ISSUE_SEVERITIES,
    ISSUE_STATUSES,
    ROLES,
    TENANT_STATUSES,
    sql_in,
)

UUID_PK = UUID(as_uuid=True)
NOW = text("now()")
NEW_UUID = text("gen_random_uuid()")


class Base(DeclarativeBase):
    # Predictable constraint/index names, so migrations can refer to them later.
    metadata = MetaData(
        naming_convention={
            "pk": "pk_%(table_name)s",
            "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
            "uq": "uq_%(table_name)s_%(column_0_name)s",
            "ck": "ck_%(table_name)s_%(constraint_name)s",
            "ix": "ix_%(column_0_label)s",
        }
    )


class Tenant(Base):
    __tablename__ = "tenants"
    __table_args__ = (CheckConstraint(f"status IN {sql_in(TENANT_STATUSES)}", name="status"),)

    id: Mapped[str] = mapped_column(Text, primary_key=True)  # readable slug, e.g. "hospital"
    name: Mapped[str] = mapped_column(Text)
    plugin_id: Mapped[str] = mapped_column(Text)  # which domain plugin serves this tenant
    status: Mapped[str] = mapped_column(Text, server_default="live")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=NOW)


class User(Base):
    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint(f"role IN {sql_in(ROLES)}", name="role"),
        # platform staff belong to no tenant; everyone else belongs to exactly one
        CheckConstraint(
            "(role = 'platform_staff') = (tenant_id IS NULL)", name="tenant_matches_role"
        ),
        # One Kontor user per identity at the identity provider.
        UniqueConstraint("idp_issuer", "idp_subject", name="uq_users_idp_identity"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID_PK, primary_key=True, server_default=NEW_UUID)
    tenant_id: Mapped[str | None] = mapped_column(ForeignKey("tenants.id"), index=True)
    name: Mapped[str] = mapped_column(Text)
    email: Mapped[str] = mapped_column(Text, unique=True)
    role: Mapped[str] = mapped_column(Text)
    mfa_enabled: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))
    last_login_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Link to the identity provider (Keycloak): token "iss" + "sub". Set on first sign-in.
    # Passwords are NOT stored here; they live only at the identity provider.
    idp_issuer: Mapped[str | None] = mapped_column(Text)
    idp_subject: Mapped[str | None] = mapped_column(Text)


class Conversation(Base):
    __tablename__ = "conversations"
    __table_args__ = (
        CheckConstraint(f"channel IN {sql_in(CHANNELS)}", name="channel"),
        CheckConstraint(f"status IN {sql_in(CONVERSATION_STATUSES)}", name="status"),
        Index("ix_conversations_tenant_started", "tenant_id", text("started_at DESC"), "id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID_PK, primary_key=True, server_default=NEW_UUID)
    tenant_id: Mapped[str] = mapped_column(ForeignKey("tenants.id"))
    ref: Mapped[str] = mapped_column(
        Text, unique=True, server_default=text("'C-' || nextval('conversation_ref_seq')")
    )
    channel: Mapped[str] = mapped_column(Text)
    contact_name: Mapped[str] = mapped_column(Text)
    contact: Mapped[str | None] = mapped_column(Text)
    summary: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text)
    # Generic markers set by plugins, e.g. the hospital plugin's "emergency".
    flags: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default=text("'{}'"))
    # Plugin-specific fields, validated by the plugin (from the plugin milestone on).
    attributes: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'"))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))


class Message(Base):
    __tablename__ = "messages"

    id: Mapped[uuid.UUID] = mapped_column(UUID_PK, primary_key=True, server_default=NEW_UUID)
    tenant_id: Mapped[str] = mapped_column(ForeignKey("tenants.id"))
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("conversations.id", ondelete="CASCADE"), index=True
    )
    role: Mapped[str] = mapped_column(Text)  # "user" | "agent" | "staff" | "system"
    content: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=NOW)


class Action(Base):
    """Something the agent wants to do or did. Used from the agent milestone on."""

    __tablename__ = "actions"

    id: Mapped[uuid.UUID] = mapped_column(UUID_PK, primary_key=True, server_default=NEW_UUID)
    tenant_id: Mapped[str] = mapped_column(ForeignKey("tenants.id"))
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("conversations.id", ondelete="CASCADE"), index=True
    )
    type: Mapped[str] = mapped_column(Text)
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'"))
    status: Mapped[str] = mapped_column(Text, server_default="pending")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=NOW)


class SupportIssue(Base):
    __tablename__ = "support_issues"
    __table_args__ = (
        CheckConstraint(f"category IN {sql_in(ISSUE_CATEGORIES)}", name="category"),
        CheckConstraint(f"severity IN {sql_in(ISSUE_SEVERITIES)}", name="severity"),
        CheckConstraint(f"status IN {sql_in(ISSUE_STATUSES)}", name="status"),
        Index("ix_support_issues_tenant_created", "tenant_id", text("created_at DESC")),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID_PK, primary_key=True, server_default=NEW_UUID)
    ref: Mapped[str] = mapped_column(
        Text, unique=True, server_default=text("'SUP-' || nextval('support_issue_ref_seq')")
    )
    tenant_id: Mapped[str] = mapped_column(ForeignKey("tenants.id"))
    reporter_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"))
    title: Mapped[str] = mapped_column(Text)
    description: Mapped[str] = mapped_column(Text)
    category: Mapped[str] = mapped_column(Text)
    severity: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text, server_default="open")
    related_conversation_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("conversations.id", ondelete="SET NULL")
    )
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=NOW)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=NOW)


class SecuritySettings(Base):
    __tablename__ = "security_settings"

    tenant_id: Mapped[str] = mapped_column(ForeignKey("tenants.id"), primary_key=True)
    mfa_required: Mapped[bool] = mapped_column(Boolean)
    sso_provider: Mapped[str | None] = mapped_column(Text)
    session_timeout_min: Mapped[int] = mapped_column(Integer)
    ip_allowlist: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default=text("'{}'"))
    data_region: Mapped[str] = mapped_column(Text)
    retention_days: Mapped[int] = mapped_column(Integer)
    pii_redaction: Mapped[bool] = mapped_column(Boolean)


class ApiKey(Base):
    __tablename__ = "api_keys"

    id: Mapped[uuid.UUID] = mapped_column(UUID_PK, primary_key=True, server_default=NEW_UUID)
    tenant_id: Mapped[str] = mapped_column(ForeignKey("tenants.id"), index=True)
    label: Mapped[str] = mapped_column(Text)
    last_four: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=NOW)
    last_used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class AuditEvent(Base):
    __tablename__ = "audit_events"
    __table_args__ = (Index("ix_audit_events_tenant_at", "tenant_id", text("at DESC")),)

    id: Mapped[uuid.UUID] = mapped_column(UUID_PK, primary_key=True, server_default=NEW_UUID)
    tenant_id: Mapped[str] = mapped_column(ForeignKey("tenants.id"))
    at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    actor: Mapped[str] = mapped_column(Text)
    action: Mapped[str] = mapped_column(Text)


class UsageSnapshot(Base):
    """API and usage numbers per tenant. Seeded now; written by tracing later."""

    __tablename__ = "usage_snapshots"

    tenant_id: Mapped[str] = mapped_column(ForeignKey("tenants.id"), primary_key=True)
    captured_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), primary_key=True)
    source: Mapped[str] = mapped_column(Text, server_default="seed")
    requests_24h: Mapped[int] = mapped_column(Integer)
    error_rate_pct: Mapped[float] = mapped_column(Float)
    p95_latency_ms: Mapped[int] = mapped_column(Integer)
    uptime_pct: Mapped[float] = mapped_column(Float)
    requests_per_hour: Mapped[list[int]] = mapped_column(ARRAY(Integer))
    active_staff: Mapped[int] = mapped_column(Integer)
    documents_indexed: Mapped[int] = mapped_column(Integer)
    automation_rate_pct: Mapped[float] = mapped_column(Float)
    avg_first_response_sec: Mapped[float] = mapped_column(Float)
